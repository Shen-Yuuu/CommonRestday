/** Rebuild the historic layered prototype from its archived sources. */
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
const root = path.resolve(import.meta.dirname, '../..');
const require = createRequire(import.meta.url);
const ts = require('D:/local/DevEcoStudio/tools/hvigor/hvigor/node_modules/typescript');
let js = '// Generated by tools/design/build-companion-layered-preview.mjs\n';
for (const name of ['CompanionMotion', 'CompanionNarrative', 'CompanionRig']) {
  const source = fs.readFileSync(path.join(root, `tools/design/legacy/${name}.ets`), 'utf8');
  js += '(() => { const exports = {};\n' + ts.transpileModule(source,
    { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText
    + `\nwindow.${name} = exports; })();\n`;
}
fs.writeFileSync(path.join(root, 'docs/prototype/assets/companion-layered-2026-10-17.js'), js);
console.log('companion layered preview: archived math/rig compiled');
